export const LABEL_TEXT_MAX = 12;
const ALLOWED = new Set(Object.keys(GLYPHS));

/** Uppercase, drop characters the font lacks, cap at 12. */
export function cleanLabelText(raw: string): string {
  return [...raw.toUpperCase()].filter((char) => ALLOWED.has(char)).join("").slice(0, LABEL_TEXT_MAX);
}

export type Rect = { x: number; y: number; w: number; h: number };

/**
 * Rectangles for a line of text, one per horizontal run of pixels, with the
 * baseline at y = 0 and the text starting at x = 0. Glyphs sit 1 pixel apart.
 */
export function textRects(text: string, pixel: number): Rect[] {
  const rects: Rect[] = [];
  [...text].forEach((char, index) => {
    const rows = (GLYPHS[char] ?? GLYPHS[" "]).split(",");
    rows.forEach((row, rowIndex) => {
      const y = (6 - rowIndex) * pixel;
      let start = -1;
      for (let col = 0; col <= 5; col += 1) {
        const on = row[col] === "#";
        if (on && start < 0) start = col;
        if (!on && start >= 0) {
          rects.push({ x: (index * 6 + start) * pixel, y, w: (col - start) * pixel, h: pixel });
          start = -1;
        }
      }
    });
  });
  return rects;
}

/** Text block size in pixels for n characters. */
export function textPixels(length: number) {
  return { w: Math.max(0, length * 6 - 1), h: 7 };
}
